"""Interface for the Bregman divergences of SPMD, injected into ``run_spmd``.

A divergence is generated by a distance-generating function w on the probability simplex:

    D(p, c) = w(p) - w(c) - <grad w(c), p - c>        (computed row-wise, one row per state)

and defines the SPMD step (course text Section 2.2; the proposal's Algorithm 1 and Section 2.3)

    pi_{k+1}(.|s) = argmin_{p in simplex}  eta * ( <Q(s, .), p> + tau * h(p) ) + D(p, pi_k(.|s)),

with h(p) = sum_a p_a log p_a the negative entropy. tau = 0 is plain SPMD; tau > 0 is the
entropy-regularized enhancement. Implementations that have no closed form for tau > 0 may raise
NotImplementedError for it.

The implementations (KL, the baseline step; squared Euclidean; Tsallis) live in
``ie692_rl.enhancements.bregman_spmd``. To add one, subclass ``BregmanDivergence``, set ``name`` and
implement ``divergence`` and ``step``; ``tests/test_divergence.py`` then checks it automatically:
D(p, p) = 0, D >= 0, rows of the step sum to one, and the step minimises ``objective``.
"""

import math
from abc import ABC, abstractmethod
from typing import ClassVar

import numpy as np

from ie692_rl.types import FloatArray


class BregmanDivergence(ABC):
    """Distance-generating function on the simplex plus its SPMD prox step."""

    name: ClassVar[str]

    @abstractmethod
    def divergence(self, p: FloatArray, center: FloatArray) -> FloatArray:
        """D(p, center) for each row (each state); shape (n_states,)."""

    @abstractmethod
    def step(self, policy: FloatArray, q: FloatArray, eta: float, tau: float = 0.0) -> FloatArray:
        """The SPMD update of ``policy`` given cost estimates ``q`` (both shaped (n_states, n_actions))."""

    def objective(
        self, p: FloatArray, policy: FloatArray, q: FloatArray, eta: float, tau: float = 0.0
    ) -> FloatArray:
        """Row-wise value of the SPMD subproblem at ``p`` (``step`` should minimise it)."""
        return eta * ((q * p).sum(axis=1) + tau * negative_entropy(p)) + self.divergence(p, policy)

    @staticmethod
    def check_step_inputs(policy: FloatArray, q: FloatArray, eta: float, tau: float) -> None:
        if policy.shape != q.shape or policy.ndim != 2:
            raise ValueError("Policy and Q must be matrices of the same shape")
        if not np.all(np.isfinite(q)):
            raise ValueError("Q estimates must be finite")
        if not (eta > 0 and not math.isnan(eta)):
            raise ValueError("Step size must be positive")
        if not (math.isfinite(tau) and tau >= 0):
            raise ValueError("Entropy weight tau must be non-negative and finite")

    @staticmethod
    def scaled_costs(q: FloatArray, eta: float) -> FloatArray:
        """eta * (Q - row minimum): non-negative, 0 at each row's best actions even for eta = inf.

        Shifting a row of Q by a constant never changes an SPMD step (the simplex constraint absorbs
        it), and the shift keeps eta * Q from overflowing for the actions that matter.
        """
        with np.errstate(over="ignore", invalid="ignore", under="ignore"):
            shifted = q - q.min(axis=1, keepdims=True)
            scaled: FloatArray = np.where(shifted > 0, eta * shifted, 0.0)
        return scaled

    def __repr__(self) -> str:
        return f"{type(self).__name__}()"


def negative_entropy(p: FloatArray) -> FloatArray:
    """h(p) = sum_a p_a log p_a per row, with 0 log 0 = 0 (never NaN for valid rows)."""
    safe = np.where(p > 0, p, 1.0)
    result: FloatArray = np.sum(np.where(p > 0, p * np.log(safe), 0.0), axis=1)
    return result
